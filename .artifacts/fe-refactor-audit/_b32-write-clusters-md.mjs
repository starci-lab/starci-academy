import fs from "node:fs"
const m = JSON.parse(fs.readFileSync(".artifacts/fe-refactor-audit/2026-08-10-b32-manifests.json", "utf8"))
const inv = JSON.parse(fs.readFileSync(".artifacts/fe-refactor-audit/2026-08-10-b32-inventory.json", "utf8"))
const lines = []
lines.push("# B32 cluster inventory")
lines.push("")
lines.push("Checkpoint: `9e86cbdf`")
lines.push(`Generated: ${m.frozenAt}`)
lines.push(`Frozen manifests: **yes** · Overlap: **${m.overlapOk ? "PASS" : "FAIL"}**`)
lines.push("")
lines.push("## Telemetry")
lines.push("")
lines.push("| Metric | Count |")
lines.push("|---|---:|")
lines.push(`| Raw messages | ${inv.telemetry.rawMessages} |`)
lines.push(`| Affected files | ${inv.telemetry.affectedFiles} |`)
lines.push(`| Errors | ${inv.telemetry.errors} |`)
lines.push(`| StarCi messages | ${inv.telemetry.starciMessages} |`)
lines.push(`| Deduped clusters | ${inv.clusters.total} |`)
lines.push(`| Actionable clusters | ${inv.clusters.actionable} |`)
lines.push("")
lines.push("## Manifests (disjoint, frozen)")
lines.push("")
for (const [k, files] of Object.entries(m.agents)) {
  lines.push(`### ${k} (${files.length} files)`)
  lines.push("")
  for (const f of files) lines.push(`- \`${f}\``)
  lines.push("")
}
fs.writeFileSync(".artifacts/fe-refactor-audit/2026-08-10-b32-clusters.md", lines.join("\n"))
console.log("ok", Object.fromEntries(Object.entries(m.agents).map(([k, v]) => [k, v.length])))
